/**
 * Calculates profession XP gain and handles Level-Up logic (1 - 100).
 */
export function addProfessionExperience(
  professions: Record<ProfessionId, ProfessionSkill>,
  professionId: ProfessionId,
  xpGain: number
): {
  updatedProfessions: Record<ProfessionId, ProfessionSkill>;
  leveledUp: boolean;
  newLevel: number;
  message: string;
} {
  const current = professions[professionId] || DEFAULT_PROFESSION_SKILLS[professionId];
  let newXp = current.xp + xpGain;
  let newLevel = current.level;
  let newMaxXp = current.maxXp;
  let leveledUp = false;

  while (newXp >= newMaxXp && newLevel < 100) {
    newXp -= newMaxXp;
    newLevel += 1;
    newMaxXp = Math.floor(newMaxXp * 1.25);
    leveledUp = true;
  }

  const updated: ProfessionSkill = {
    ...current,
    level: newLevel,
    xp: newXp,
    maxXp: newMaxXp,
    totalCraftedOrGathered: current.totalCraftedOrGathered + 1,
  };

  const updatedProfessions = {
    ...professions,
    [professionId]: updated,
  };

  const message = leveledUp
    ? `🎉 Berufsaufstieg! ${current.germanName} hat Stufe ${newLevel} erreicht!`
    : `+${xpGain} XP in ${current.germanName} erhalten.`;

  return {
    updatedProfessions,
    leveledUp,
    newLevel,
    message,
  };
}
